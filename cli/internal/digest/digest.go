// Package digest writes the compact AGENTS.md memory file consumed by agents.
//
// It is shared by the CLI "digest" command and the local web UI so both accept
// the same review/project filters and produce byte-identical output.
package digest

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/extract"
	"devlog-learn/internal/manifest"
	"devlog-learn/internal/questions"
	"devlog-learn/internal/search"
)

const marker = "# Project memory (devlog-learn)"

// Options controls one digest write.
type Options struct {
	OutDir  string
	Project string // empty/all, auto, or a project name
	Review  string // any, approved, pending, or rejected
	Limit   int
	Force   bool
}

// Result reports what was written.
type Result struct {
	Path     string
	Docs     int
	Project  string
	Review   string
	Warnings []string
}

// Write builds and writes <out>/AGENTS.md. It never includes stale documents.
func Write(store *cache.Store, opt Options, now time.Time) (Result, error) {
	review, err := NormalizeReview(opt.Review)
	if err != nil {
		return Result{}, err
	}
	limit := opt.Limit
	if limit == 0 {
		limit = 20
	}
	if limit < 1 || limit > search.MaxLimit {
		return Result{}, fmt.Errorf("limit must be between 1 and %d", search.MaxLimit)
	}
	if strings.TrimSpace(opt.OutDir) == "" {
		return Result{}, errors.New("out directory must not be empty")
	}
	if store == nil {
		return Result{}, errors.New("no cache store")
	}
	project := ResolveProject(opt.Project)
	result := Result{
		Project: displayProject(project),
		Review:  review,
	}

	infos, warnings := store.ListActiveDocs()
	result.Warnings = append(result.Warnings, warnings...)
	results := search.Search(infos, search.Options{
		Query:   "",
		Project: project,
		Review:  review,
		Limit:   limit,
		OutDir:  opt.OutDir,
	})
	result.Docs = len(results)

	path := filepath.Join(opt.OutDir, "AGENTS.md")
	if !opt.Force {
		if existing, readErr := os.ReadFile(path); readErr == nil {
			if !bytes.Contains(existing, []byte(marker)) {
				return result, fmt.Errorf("%s exists and was not generated by devlog-learn; choose another out directory or force the overwrite", path)
			}
		} else if !errors.Is(readErr, os.ErrNotExist) {
			return result, fmt.Errorf("check existing digest %s: %w", path, readErr)
		}
	}

	resolved := map[string]bool{}
	if state, stateErr := questions.Load(questions.Path(store.Root)); stateErr != nil {
		result.Warnings = append(result.Warnings, stateErr.Error())
	} else {
		resolved = state.ResolvedIDs()
	}

	content := render(now.UTC(), project, review, results, collectQuestions(infos, results, resolved, 20))
	if err := os.MkdirAll(opt.OutDir, 0o755); err != nil {
		return result, fmt.Errorf("create output directory: %w", err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return result, fmt.Errorf("write digest %s: %w", path, err)
	}
	manifestReport, manifestErr := manifest.Reconcile(opt.OutDir, "digest", []manifest.GeneratedFile{{
		Path: "AGENTS.md",
	}}, false, now.UTC())
	result.Warnings = append(result.Warnings, manifestReport.Warnings...)
	if manifestErr != nil {
		return result, manifestErr
	}
	result.Path = path
	return result, nil
}

// NormalizeReview validates the review filter shared by digest and MCP.
func NormalizeReview(value string) (string, error) {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "", "any", "*":
		return "any", nil
	case extract.ReviewApproved:
		return extract.ReviewApproved, nil
	case extract.ReviewPending:
		return extract.ReviewPending, nil
	case extract.ReviewRejected:
		return extract.ReviewRejected, nil
	default:
		return "", fmt.Errorf("invalid review filter %q (want any, approved, pending, or rejected)", value)
	}
}

// ResolveProject turns "auto" into the current directory name. Empty, "all",
// and "*" mean no project filter.
func ResolveProject(value string) string {
	value = strings.TrimSpace(value)
	if value == "" || value == "*" || strings.EqualFold(value, "all") {
		return ""
	}
	if !strings.EqualFold(value, "auto") {
		return value
	}
	cwd, err := os.Getwd()
	if err != nil {
		return ""
	}
	base := filepath.Base(cwd)
	if base == "." || base == string(filepath.Separator) || (len(base) == 2 && base[1] == ':') {
		return ""
	}
	return base
}

func displayProject(project string) string {
	if strings.TrimSpace(project) == "" {
		return "all"
	}
	return project
}

func render(now time.Time, project, review string, results []search.Result, questions []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n", marker)
	fmt.Fprintf(&b, "> Generated: %s\n", now.Format(time.RFC3339))
	fmt.Fprintf(&b, "> Project: %s\n", displayProject(project))
	fmt.Fprintf(&b, "> Review filter: %s\n", review)
	fmt.Fprintf(&b, "> Source: local Claude Code / Codex sessions. Treat this as historical memory, not current truth.\n\n")

	b.WriteString("## How to use\n\n")
	b.WriteString("- Search this file by title, tag, or error signature before implementing or debugging.\n")
	b.WriteString("- Prefer `approved` documents and high `evidence_verified/evidence_checked` ratios.\n")
	b.WriteString("- Verify claims against the current code and command output before acting.\n")
	b.WriteString("- Read the full Markdown at the listed path, or run `devlog-learn mcp` for on-demand retrieval.\n\n")

	fmt.Fprintf(&b, "## Documents (%d)\n\n", len(results))
	if len(results) == 0 {
		b.WriteString("No documents matched. Run `devlog-learn run` first, or relax `--review` / `--project`.\n")
		return b.String()
	}
	b.WriteString("| ID | Title | Project | Tags | Confidence | Evidence | Review | Path |\n")
	b.WriteString("|---|---|---|---|---:|---|---|---|\n")
	for _, result := range results {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %.2f | %d/%d | %s | %s |\n",
			mdCell(result.ID, 0),
			mdCell(result.Title, 80),
			mdCell(result.Project, 40),
			mdCell(strings.Join(result.Tags, ", "), 80),
			result.Confidence,
			result.EvidenceVerified, result.EvidenceChecked,
			mdCell(result.ReviewStatus, 20),
			mdCell(result.MarkdownPath, 0),
		)
	}

	if len(questions) > 0 {
		b.WriteString("\n## Open questions\n\n")
		for _, question := range questions {
			b.WriteString("- " + question + "\n")
		}
	}
	return b.String()
}

func collectQuestions(infos []cache.DocInfo, results []search.Result, resolved map[string]bool, limit int) []string {
	byID := make(map[string]*extract.Doc, len(infos))
	for _, info := range infos {
		if info.Doc != nil {
			byID[info.ID] = info.Doc
		}
	}
	seen := make(map[string]bool)
	out := make([]string, 0, limit)
	for _, result := range results {
		doc := byID[result.ID]
		if doc == nil {
			continue
		}
		for _, question := range doc.OpenQuestions {
			question = strings.Join(strings.Fields(strings.TrimSpace(question)), " ")
			if question == "" || seen[question] {
				continue
			}
			if resolved[questions.NewID(doc.ID, question)] {
				continue
			}
			seen[question] = true
			out = append(out, fmt.Sprintf("[%s] %s", result.ID, question))
			if len(out) >= limit {
				return out
			}
		}
	}
	return out
}

func mdCell(value string, maxRunes int) string {
	value = strings.Join(strings.Fields(strings.TrimSpace(value)), " ")
	value = strings.ReplaceAll(value, "|", "\\|")
	if maxRunes > 0 {
		runes := []rune(value)
		if len(runes) > maxRunes {
			value = string(runes[:maxRunes]) + "…"
		}
	}
	if value == "" {
		return "-"
	}
	return value
}
