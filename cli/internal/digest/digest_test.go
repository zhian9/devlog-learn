package digest

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/extract"
)

var testTime = time.Date(2026, 11, 12, 10, 0, 0, 0, time.UTC)

func TestWriteCreatesDigestAndSkipsStale(t *testing.T) {
	store := fixtureStore(t)
	out := t.TempDir()
	result, err := Write(store, Options{OutDir: out, Review: "any", Limit: 10}, testTime)
	if err != nil {
		t.Fatal(err)
	}
	if result.Docs != 1 || result.Project != "all" || result.Review != "any" {
		t.Fatalf("result = %+v", result)
	}
	data, err := os.ReadFile(result.Path)
	if err != nil {
		t.Fatal(err)
	}
	content := string(data)
	if !strings.Contains(content, "# Project memory (devlog-learn)") {
		t.Fatalf("missing marker: %s", content)
	}
	if !strings.Contains(content, "Fixture active") || strings.Contains(content, "Fixture stale") {
		t.Fatalf("stale filter failed: %s", content)
	}
	if !strings.Contains(content, "[docs-active] fixture question") {
		t.Fatalf("open question missing: %s", content)
	}
}

func TestWriteFiltersReviewAndProject(t *testing.T) {
	store := fixtureStore(t)
	out := t.TempDir()
	result, err := Write(store, Options{OutDir: out, Review: "approved", Project: "demo", Limit: 10}, testTime)
	if err != nil {
		t.Fatal(err)
	}
	if result.Docs != 0 {
		t.Fatalf("expected no approved docs, got %+v", result)
	}
	data, _ := os.ReadFile(result.Path)
	if !strings.Contains(string(data), "No documents matched") {
		t.Fatalf("unexpected digest: %s", data)
	}
}

func TestWriteRefusesForeignAgentsFile(t *testing.T) {
	store := fixtureStore(t)
	out := t.TempDir()
	path := filepath.Join(out, "AGENTS.md")
	if err := os.WriteFile(path, []byte("# hand written\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Write(store, Options{OutDir: out}, testTime); err == nil ||
		!strings.Contains(err.Error(), "not generated by devlog-learn") {
		t.Fatalf("error = %v", err)
	}
	if data, _ := os.ReadFile(path); string(data) != "# hand written\n" {
		t.Fatalf("foreign file changed: %q", data)
	}
	if _, err := Write(store, Options{OutDir: out, Force: true}, testTime); err != nil {
		t.Fatalf("force: %v", err)
	}
}

func TestNormalizeReview(t *testing.T) {
	for _, value := range []string{"", "any", "*", "approved", "PENDING", "rejected"} {
		if _, err := NormalizeReview(value); err != nil {
			t.Fatalf("NormalizeReview(%q): %v", value, err)
		}
	}
	if _, err := NormalizeReview("bogus"); err == nil {
		t.Fatal("expected invalid review error")
	}
}

func fixtureStore(t *testing.T) *cache.Store {
	t.Helper()
	store := &cache.Store{Root: t.TempDir()}
	active := &extract.Doc{
		SchemaVersion: 1,
		ID:            "docs-active",
		Slug:          "fixture-active",
		Title:         "Fixture active",
		Project:       "demo",
		KnowledgeType: "bug_fix",
		ReviewStatus:  extract.ReviewPending,
		Lifecycle:     extract.LifecycleActive,
		OccurredAt:    testTime.Add(-time.Hour),
		Tags:          []string{"go"},
		OpenQuestions: []string{"fixture question"},
		Confidence:    0.7,
		Validation:    extract.Validation{EvidenceChecked: 2, EvidenceVerified: 2},
	}
	stale := &extract.Doc{
		SchemaVersion: 1,
		ID:            "docs-stale",
		Slug:          "fixture-stale",
		Title:         "Fixture stale",
		Project:       "demo",
		KnowledgeType: "bug_fix",
		ReviewStatus:  extract.ReviewPending,
		Lifecycle:     extract.LifecycleStale,
		OccurredAt:    testTime.Add(-2 * time.Hour),
	}
	for _, doc := range []*extract.Doc{active, stale} {
		if err := store.SaveDoc(doc); err != nil {
			t.Fatal(err)
		}
	}
	return store
}
