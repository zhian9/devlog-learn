// Package export writes the user-facing artifacts: Markdown documents and
// JSON/Markdown indexes. CLI commands and the local UI share this package so
// they cannot drift apart.
package export

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/extract"
	"devlog-learn/internal/index"
	"devlog-learn/internal/manifest"
	"devlog-learn/internal/render"
)

// RenderReport lists what Render wrote.
type RenderReport struct {
	Written      int
	StaleSkipped int
	Pruned       int
	PruneSkipped int
	Paths        []string
	Warnings     []string
}

// RenderProfileOptions controls one Markdown render profile.
type RenderProfileOptions struct {
	IncludeStale bool
	Profile      string
	Prune        bool
}

// Render writes one Markdown file per selected document using the agent
// profile. Stale documents are skipped unless includeStale is set. Existing
// files are overwritten and nothing is deleted.
func Render(store *cache.Store, outDir string, includeStale bool) (RenderReport, error) {
	return RenderProfile(store, outDir, includeStale, ProfileAgent)
}

const (
	// ProfileAgent is the stable, agent-facing Markdown contract.
	ProfileAgent = "agent"
	// ProfileLearning is the human-facing Chinese learning template.
	ProfileLearning = "learning"
)

// RenderProfile writes one Markdown file per selected document using the named
// profile. The learning profile writes *.learn.md so agent-facing files are
// left untouched.
func RenderProfile(store *cache.Store, outDir string, includeStale bool, profile string) (RenderReport, error) {
	return RenderProfileWithOptions(store, outDir, RenderProfileOptions{
		IncludeStale: includeStale,
		Profile:      profile,
	})
}

// RenderProfileWithOptions renders one profile and optionally prunes stale
// files previously generated by that profile.
func RenderProfileWithOptions(store *cache.Store, outDir string, opts RenderProfileOptions) (RenderReport, error) {
	includeStale := opts.IncludeStale
	profile := opts.Profile
	report := RenderReport{}
	if store == nil {
		return report, fmt.Errorf("no cache store")
	}
	profile = strings.ToLower(strings.TrimSpace(profile))
	if profile == "" {
		profile = ProfileAgent
	}
	if profile != ProfileAgent && profile != ProfileLearning {
		return report, fmt.Errorf("unknown render profile %q (want %s or %s)", profile, ProfileAgent, ProfileLearning)
	}
	infos, warnings := store.ListActiveDocs()
	if includeStale {
		infos, warnings = store.ListDocs()
	} else {
		all, _ := store.ListDocs()
		report.StaleSkipped = len(all) - len(infos)
	}
	report.Warnings = warnings

	docs := make([]*extract.Doc, 0, len(infos))
	for _, info := range infos {
		if info.Doc != nil {
			docs = append(docs, info.Doc)
		}
	}
	plans := []render.Plan(nil)
	if len(docs) > 0 {
		plans = render.PlanDocs(docs)
		if profile == ProfileLearning {
			plans = render.LearnPlans(docs)
		}
	}
	generated := make([]manifest.GeneratedFile, 0, len(plans))
	for _, plan := range plans {
		path := filepath.Join(outDir, filepath.FromSlash(plan.Path))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return report, fmt.Errorf("create output directory for %s: %w", plan.Path, err)
		}
		content := render.Markdown(plan.Doc)
		if profile == ProfileLearning {
			content = render.LearnMarkdown(plan.Doc)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return report, fmt.Errorf("write %s: %w", path, err)
		}
		report.Paths = append(report.Paths, path)
		report.Written++
		generated = append(generated, manifest.GeneratedFile{
			Path:  plan.Path,
			DocID: plan.Doc.ID,
		})
	}
	manifestReport, err := manifest.Reconcile(outDir, profile, generated, opts.Prune, time.Now().UTC())
	report.Pruned = manifestReport.Pruned
	report.PruneSkipped = manifestReport.Skipped
	report.Warnings = append(report.Warnings, manifestReport.Warnings...)
	return report, err
}

// BuildIndex writes global and per-project index.json/README.md files. It
// always uses active documents.
func BuildIndex(store *cache.Store, outDir string, now time.Time) (index.Report, []string, error) {
	return BuildIndexWithOptions(store, outDir, now, index.WriteOptions{})
}

// BuildIndexWithOptions writes indexes with explicit pruning behavior.
func BuildIndexWithOptions(store *cache.Store, outDir string, now time.Time, opts index.WriteOptions) (index.Report, []string, error) {
	if store == nil {
		return index.Report{}, nil, fmt.Errorf("no cache store")
	}
	infos, warnings := store.ListActiveDocs()
	report, err := index.WriteWithOptions(outDir, infos, now, opts)
	warnings = append(warnings, report.Warnings...)
	return report, warnings, err
}
