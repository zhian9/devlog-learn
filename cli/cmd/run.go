package main

import (
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/spf13/cobra"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/export"
	"devlog-learn/internal/index"
	"devlog-learn/internal/pipeline"
)

type runOptions struct {
	extractOptions
	prune bool
}

func newRunCmd() *cobra.Command {
	opt := &runOptions{}
	cmd := &cobra.Command{
		Use:   "run",
		Short: "Extract, render Markdown, and build indexes in one command",
		Long: `Run the complete pipeline:

  1. incremental extraction (same cursor/cache semantics as "extract")
  2. render active Docs to <out>/<project>/<date>-<slug>.md
  3. build <out>/index.json, <out>/README.md and per-project indexes

By default only ONE new segment is extracted per run because each cache miss
costs a model call. Use --segments 0 for all prepared segments, or select
specific sessions/segments with --session/--segment (see "sessions").`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return runRun(cmd, opt)
		},
	}
	addExtractionFlags(cmd, &opt.extractOptions)
	cmd.Flags().StringVar(&opt.outDir, "out", ".devlog-docs", "output directory for Markdown and indexes")
	cmd.Flags().BoolVar(&opt.prune, "prune", false, "remove stale files previously generated by this run")
	return cmd
}

func runRun(cmd *cobra.Command, opt *runOptions) error {
	if err := validateExtractOptions(cmd, &opt.extractOptions); err != nil {
		return err
	}
	if strings.TrimSpace(opt.outDir) == "" {
		return fmt.Errorf("--out must not be empty")
	}
	cutoff, redactCfg, err := opt.cutoffAndRedact()
	if err != nil {
		return err
	}

	stderr := cmd.ErrOrStderr()
	stdout := cmd.OutOrStdout()
	logger := newLogger()

	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()

	runOptions := opt.pipelineRunOptions(cutoff, redactCfg, logger)
	runOptions.CacheLock = lock
	result, runErr := pipeline.Run(cmd.Context(), runOptions)
	if result == nil {
		return runErr
	}
	printDryRunWarnings(stderr, result.Warnings)
	if len(result.Reports) == 0 {
		fmt.Fprintf(stderr, "no segments to extract (files=%d parsed=%d skipped=%d)\n",
			result.Files, result.Parsed, result.Skipped)
	}
	printExtractionReports(stderr, result)
	printExtractionSummary(stderr, result)

	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return errors.Join(runErr, err)
	}
	renderReport, renderErr := export.RenderProfileWithOptions(store, opt.outDir, export.RenderProfileOptions{
		Profile: export.ProfileAgent,
		Prune:   opt.prune,
	})
	printDryRunWarnings(stderr, renderReport.Warnings)
	indexReport, indexWarnings, indexErr := export.BuildIndexWithOptions(store, opt.outDir, time.Now(), index.WriteOptions{
		Prune: opt.prune,
	})
	printDryRunWarnings(stderr, indexWarnings)

	fmt.Fprintf(stderr, "output: markdown=%d skipped_stale=%d pruned=%d docs=%d projects=%d out=%s\n",
		renderReport.Written, renderReport.StaleSkipped,
		renderReport.Pruned+indexReport.Pruned, indexReport.Docs, indexReport.Projects,
		strings.TrimSpace(opt.outDir))
	if renderErr == nil && indexErr == nil {
		fmt.Fprintln(stdout, strings.TrimSpace(opt.outDir))
	}
	return errors.Join(runErr, renderErr, indexErr)
}
