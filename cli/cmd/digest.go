package main

import (
	"fmt"
	"strings"
	"time"

	"github.com/spf13/cobra"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/digest"
)

type digestOptions struct {
	cacheDir string
	outDir   string
	project  string
	review   string
	limit    int
	force    bool
}

func newDigestCmd() *cobra.Command {
	opt := &digestOptions{}
	cmd := &cobra.Command{
		Use:   "digest",
		Short: "Write a compact AGENTS.md memory digest for agents",
		Long: `Write <out>/AGENTS.md with the most relevant active Docs, their review and
evidence status, tags, paths, and open questions.

This is the zero-infrastructure Agent integration: any agent that reads
AGENTS.md can use the digest without an MCP client. For on-demand retrieval,
use "devlog-learn mcp" instead.

Only active Docs are included. Stale Docs stay on disk but never enter the
digest. Use --review approved for a human-curated view, or the default "any"
to include pending Docs (their review status is shown).`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return runDigest(cmd, opt)
		},
	}
	flags := cmd.Flags()
	flags.StringVar(&opt.cacheDir, "cache-dir", ".devlog-cache", "cache directory containing docs/")
	flags.StringVar(&opt.outDir, "out", ".devlog-docs", "output directory for AGENTS.md")
	flags.StringVar(&opt.project, "project", "", "project filter: empty/all, auto, or a project name")
	flags.StringVar(&opt.review, "review", "any", "review filter: any, approved, pending, or rejected")
	flags.IntVar(&opt.limit, "limit", 20, "maximum documents to include (1-50)")
	flags.BoolVar(&opt.force, "force", false, "overwrite an existing AGENTS.md that was not generated by devlog-learn")
	return cmd
}

func runDigest(cmd *cobra.Command, opt *digestOptions) error {
	if strings.TrimSpace(opt.outDir) == "" {
		return fmt.Errorf("--out must not be empty")
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()
	result, err := digest.Write(&cache.Store{Root: opt.cacheDir}, digest.Options{
		OutDir:  opt.outDir,
		Project: opt.project,
		Review:  opt.review,
		Limit:   opt.limit,
		Force:   opt.force,
	}, time.Now().UTC())
	if err != nil {
		return err
	}
	for _, warning := range result.Warnings {
		fmt.Fprintf(cmd.ErrOrStderr(), "digest: %s\n", warning)
	}
	fmt.Fprintf(cmd.ErrOrStderr(), "digest: docs=%d project=%s review=%s path=%s\n",
		result.Docs, result.Project, result.Review, result.Path)
	fmt.Fprintln(cmd.OutOrStdout(), result.Path)
	return nil
}
