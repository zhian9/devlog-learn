func TestDigestCommandWritesAgentsMemory(t *testing.T) {
	approved := commandDoc("aaa", "demo", "Fix cache eviction", outputTime, "cache", "go")
	approved.ReviewStatus = extract.ReviewApproved
	approved.OpenQuestions = []string{"Why does the TTL expire early?"}
	pending := commandDoc("bbb", "demo", "Session selection", outputTime.Add(-time.Hour), "cli", "go")
	pending.OpenQuestions = []string{"Is the wizard enough?"}
	stale := commandDoc("ccc", "demo", "Old cache note", outputTime.Add(-2*time.Hour), "cache")
	stale.Lifecycle = extract.LifecycleStale

	cacheDir := seedCache(t, approved, pending, stale)
	out := t.TempDir()

	stdout, stderr, err := runCommand("digest", "--cache-dir", cacheDir, "--out", out, "--limit", "10")
	if err != nil {
		t.Fatalf("digest: %v", err)
	}
	path := filepath.Join(out, "AGENTS.md")
	if !strings.Contains(stdout, path) {
		t.Fatalf("stdout = %q", stdout)
	}
	if !strings.Contains(stderr, "digest: docs=2") {
		t.Fatalf("stderr = %q", stderr)
	}

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read digest: %v", err)
	}
	content := string(data)
	for _, want := range []string{
		"# Project memory",
		"Fix cache eviction",
		"Session selection",
		"approved",
		"pending",
		"demo/2026-06-01-fix-cache-eviction.md",
		"[aaa] Why does the TTL expire early?",
		"[bbb] Is the wizard enough?",
	} {
		if !strings.Contains(content, want) {
			t.Fatalf("digest missing %q:\n%s", want, content)
		}
	}
	if strings.Contains(content, "Old cache note") {
		t.Fatalf("stale doc leaked into digest:\n%s", content)
	}
}

func TestDigestCommandReviewFilterAndLimit(t *testing.T) {
	approved := commandDoc("aaa", "demo", "Fix cache eviction", outputTime, "cache")
	approved.ReviewStatus = extract.ReviewApproved
	pending := commandDoc("bbb", "demo", "Session selection", outputTime.Add(-time.Hour), "cli")
	cacheDir := seedCache(t, approved, pending)

	out := t.TempDir()
	if _, _, err := runCommand("digest", "--cache-dir", cacheDir, "--out", out, "--review", "approved"); err != nil {
		t.Fatalf("digest: %v", err)
	}
	content := readDigest(t, out)
	if !strings.Contains(content, "Fix cache eviction") || strings.Contains(content, "Session selection") {
		t.Fatalf("review filter failed:\n%s", content)
	}

	out = t.TempDir()
	if _, _, err := runCommand("digest", "--cache-dir", cacheDir, "--out", out, "--limit", "1"); err != nil {
		t.Fatalf("digest: %v", err)
	}
	content = readDigest(t, out)
	if !strings.Contains(content, "Fix cache eviction") || strings.Contains(content, "Session selection") {
		t.Fatalf("limit failed:\n%s", content)
	}
}

func TestDigestCommandEmptyCache(t *testing.T) {
	out := t.TempDir()
	cacheDir := t.TempDir()
	if _, _, err := runCommand("digest", "--cache-dir", cacheDir, "--out", out); err != nil {
		t.Fatalf("digest: %v", err)
	}
	content := readDigest(t, out)
	if !strings.Contains(content, "No documents matched") {
		t.Fatalf("empty digest:\n%s", content)
	}
}

func TestDigestCommandRefusesToOverwriteForeignAgentsFile(t *testing.T) {
	out := t.TempDir()
	path := filepath.Join(out, "AGENTS.md")
	if err := os.WriteFile(path, []byte("# Hand-written agent instructions\n"), 0o644); err != nil {
		t.Fatalf("seed AGENTS.md: %v", err)
	}

	_, _, err := runCommand("digest", "--cache-dir", t.TempDir(), "--out", out)
	if err == nil || !strings.Contains(err.Error(), "not generated by devlog-learn") {
		t.Fatalf("error = %v", err)
	}
	data, _ := os.ReadFile(path)
	if !strings.Contains(string(data), "Hand-written") {
		t.Fatalf("foreign file was modified:\n%s", data)
	}

	if _, _, err := runCommand("digest", "--cache-dir", t.TempDir(), "--out", out, "--force"); err != nil {
		t.Fatalf("digest --force: %v", err)
	}
	if content := readDigest(t, out); !strings.Contains(content, "# Project memory") {
		t.Fatalf("--force did not overwrite:\n%s", content)
	}
}

func TestDigestCommandRejectsInvalidReview(t *testing.T) {
	_, _, err := runCommand("digest", "--cache-dir", t.TempDir(), "--out", t.TempDir(), "--review", "bogus")
	if err == nil || !strings.Contains(err.Error(), "invalid review filter") {
		t.Fatalf("error = %v", err)
	}
}

func readDigest(t *testing.T, out string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(out, "AGENTS.md"))
	if err != nil {
		t.Fatalf("read digest: %v", err)
	}
	return string(data)
}
