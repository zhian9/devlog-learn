func runExperienceList(cmd *cobra.Command, opt *experienceOptions) error {
	store, infos, state, warnings, err := loadExperienceContext(opt.cacheDir)
	if err != nil {
		return err
	}
	exps := experience.Build(infos, store, state, time.Now())
	printDryRunWarnings(cmd.ErrOrStderr(), warnings)

	paths := render.ExperiencePaths(exps)
	stdout := cmd.OutOrStdout()
	if opt.asJSON {
		type item struct {
			experience.Summary
			MarkdownPath string `json:"markdown_path"`
		}
		items := make([]item, 0, len(exps))
		for _, exp := range exps {
			items = append(items, item{
				Summary:      experience.Summarize(exp),
				MarkdownPath: paths[exp.Project],
			})
		}
		if warnings == nil {
			warnings = []string{}
		}
		encoder := json.NewEncoder(stdout)
		encoder.SetIndent("", "  ")
		if err := encoder.Encode(struct {
			Count       int      `json:"count"`
			Experiences []item   `json:"experiences"`
			Warnings    []string `json:"warnings,omitempty"`
		}{Count: len(items), Experiences: items, Warnings: warnings}); err != nil {
			return err
		}
	} else {
		writer := tabwriter.NewWriter(stdout, 0, 0, 2, ' ', 0)
		fmt.Fprintln(writer, "PROJECT\tKIND\tSOURCE\tDOCS\tPERIOD\tSUGGESTED\tPATH")
		for _, exp := range exps {
			suggested := experience.SuggestKind(exp.Project, exp.Paths)
			fmt.Fprintf(writer, "%s\t%s\t%s\t%d\t%s\t%s\t%s\n",
				exp.Project, exp.KindLabel, experienceKindSourceLabel(exp.KindSource), exp.Docs,
				emptyDash(exp.Period), emptyDash(suggested), paths[exp.Project])
		}
		if err := writer.Flush(); err != nil {
			return err
		}
		if len(exps) == 0 {
			fmt.Fprintln(stdout, "no experiences yet (extract or run first)")
		}
	}

	docs := 0
	for _, exp := range exps {
		docs += exp.Docs
	}
	fmt.Fprintf(cmd.ErrOrStderr(), "experiences: count=%d docs=%d\n", len(exps), docs)
	return nil
}

func runExperienceShow(cmd *cobra.Command, opt *experienceOptions) error {
	store, infos, state, warnings, err := loadExperienceContext(opt.cacheDir)
	if err != nil {
		return err
	}
	exps := experience.Build(infos, store, state, time.Now())
	exp, err := findExperience(exps, opt.project)
	if err != nil {
		return err
	}
	printDryRunWarnings(cmd.ErrOrStderr(), warnings)

	if opt.asJSON {
		encoder := json.NewEncoder(cmd.OutOrStdout())
		encoder.SetIndent("", "  ")
		return encoder.Encode(exp)
	}
	fmt.Fprint(cmd.OutOrStdout(), render.ExperienceMarkdown(exp, experienceDocPaths(infos)))
	return nil
}

func runExperienceRender(cmd *cobra.Command, opt *experienceOptions) error {
	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return err
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()

	state, err := experience.LoadState(experience.StatePath(opt.cacheDir))
	if err != nil {
		return err
	}
	report, err := export.RenderExperiences(store, opt.outDir, state, export.ExperienceRenderOptions{
		Prune:   opt.prune,
		Project: opt.project,
	})
	printDryRunWarnings(cmd.ErrOrStderr(), report.Warnings)
	if err != nil {
		return err
	}
	for _, path := range report.Paths {
		fmt.Fprintln(cmd.OutOrStdout(), path)
	}
	if report.Written == 0 {
		fmt.Fprintln(cmd.ErrOrStderr(), "no experience output written")
	}
	fmt.Fprintf(cmd.ErrOrStderr(), "summary: written=%d pruned=%d prune_skipped=%d out=%s\n",
		report.Written, report.Pruned, report.PruneSkipped, strings.TrimSpace(opt.outDir))
	return nil
}

func runExperienceSet(cmd *cobra.Command, opt *experienceOptions) error {
	if strings.TrimSpace(opt.project) == "" {
		return errors.New("--project is required")
	}
	kind := ""
	if cmd.Flags().Changed("kind") {
		kind = experience.NormalizeKind(opt.kind)
		if kind == "" {
			return fmt.Errorf("invalid --kind %q (want project, internship, work, or course)", opt.kind)
		}
	}
	if cmd.Flags().Changed("start") && !validExperiencePeriod(opt.start) {
		return fmt.Errorf("invalid --start %q (want YYYY-MM or YYYY-MM-DD)", opt.start)
	}
	if cmd.Flags().Changed("end") && !validExperiencePeriod(opt.end) {
		return fmt.Errorf("invalid --end %q (want YYYY-MM or YYYY-MM-DD)", opt.end)
	}

	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return err
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()

	state, err := experience.LoadState(experience.StatePath(opt.cacheDir))
	if err != nil {
		return err
	}
	infos, warnings := store.ListActiveDocs()
	printDryRunWarnings(cmd.ErrOrStderr(), warnings)
	exp, err := findExperience(experience.Build(infos, store, state, time.Now()), opt.project)
	if err != nil {
		return err
	}

	meta, _ := state.Get(exp.Project)
	changed := false
	if cmd.Flags().Changed("kind") {
		meta.Kind = kind
		meta.Confirmed = true
		changed = true
	}
	if cmd.Flags().Changed("org") {
		meta.Organization = strings.TrimSpace(opt.organization)
		changed = true
	}
	if cmd.Flags().Changed("role") {
		meta.Role = strings.TrimSpace(opt.role)
		changed = true
	}
	if cmd.Flags().Changed("start") {
		meta.Start = strings.TrimSpace(opt.start)
		changed = true
	}
	if cmd.Flags().Changed("end") {
		meta.End = strings.TrimSpace(opt.end)
		changed = true
	}
	if cmd.Flags().Changed("headline") {
		meta.Headline = strings.TrimSpace(opt.headline)
		changed = true
	}
	if !changed {
		return errors.New("nothing to update; pass at least one of --kind, --org, --role, --start, --end, or --headline")
	}

	state.Set(exp.Project, meta)
	now := time.Now()
	if err := state.Save(experience.StatePath(opt.cacheDir), now); err != nil {
		return err
	}
	effectiveKind := meta.Kind
	if effectiveKind == "" {
		effectiveKind = exp.Kind
	}
	fmt.Fprintf(cmd.OutOrStdout(), "updated experience project=%s kind=%s source=%s\n",
		exp.Project, experience.KindLabel(effectiveKind), experienceKindSourceLabel(exp.KindSource))
	return nil
}

func runExperienceUnset(cmd *cobra.Command, opt *experienceOptions) error {
	if strings.TrimSpace(opt.project) == "" {
		return errors.New("--project is required")
	}
	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return err
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()

	state, err := experience.LoadState(experience.StatePath(opt.cacheDir))
	if err != nil {
		return err
	}
	if state.Unset(opt.project) {
		if err := state.Save(experience.StatePath(opt.cacheDir), time.Now()); err != nil {
			return err
		}
		fmt.Fprintf(cmd.OutOrStdout(), "removed experience metadata project=%s\n", strings.TrimSpace(opt.project))
		return nil
	}

	infos, warnings := store.ListActiveDocs()
	printDryRunWarnings(cmd.ErrOrStderr(), warnings)
	exp, err := findExperience(experience.Build(infos, store, state, time.Now()), opt.project)
	if err != nil {
		return err
	}
	if !state.Unset(exp.Project) {
		return fmt.Errorf("no manual experience metadata for project %q", exp.Project)
	}
	if err := state.Save(experience.StatePath(opt.cacheDir), time.Now()); err != nil {
		return err
	}
	fmt.Fprintf(cmd.OutOrStdout(), "removed experience metadata project=%s\n", exp.Project)
	return nil
}

func runExperienceChecklist(cmd *cobra.Command, opt *experienceOptions) error {
	store, infos, state, warnings, err := loadExperienceContext(opt.cacheDir)
	if err != nil {
		return err
	}
	exp, err := findExperience(experience.Build(infos, store, state, time.Now()), opt.project)
	if err != nil {
		return err
	}
	printDryRunWarnings(cmd.ErrOrStderr(), warnings)

	stdout := cmd.OutOrStdout()
	for _, item := range exp.ReviewChecklist {
		fmt.Fprintf(stdout, "- [ ] %s", item.Text)
		if item.DocID != "" {
			fmt.Fprintf(stdout, "（`%s`）", item.DocID)
		}
		fmt.Fprintln(stdout)
	}
	if len(exp.ReviewChecklist) == 0 {
		fmt.Fprintln(stdout, "no review items")
	}
	fmt.Fprintf(cmd.ErrOrStderr(), "checklist: project=%s items=%d\n", exp.Project, len(exp.ReviewChecklist))
	return nil
}

func runExperienceSynthesize(cmd *cobra.Command, opt *experienceOptions) error {
	if strings.TrimSpace(opt.project) == "" {
		return errors.New("--project is required")
	}
	provider := strings.ToLower(strings.TrimSpace(opt.provider))
	bin := ""
	switch provider {
	case "", "claude-code":
		provider = "claude-code"
		bin = opt.claudeBin
	case "codex":
		bin = opt.codexBin
	default:
		return fmt.Errorf("unsupported --provider %q (want claude-code or codex)", opt.provider)
	}

	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return err
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()

	state, err := experience.LoadState(experience.StatePath(opt.cacheDir))
	if err != nil {
		return err
	}
	infos, warnings := store.ListActiveDocs()
	printDryRunWarnings(cmd.ErrOrStderr(), warnings)
	exp, err := findExperience(experience.Build(infos, store, state, time.Now()), opt.project)
	if err != nil {
		return err
	}
	docs := experience.DocsForProject(infos, exp.Project)
	if len(docs) == 0 {
		return fmt.Errorf("project %q has no active Docs to synthesize", exp.Project)
	}

	client, err := extract.NewCLIClient(extract.CLIOptions{
		Provider: provider,
		Bin:      bin,
		Model:    opt.model,
		Timeout:  opt.timeout,
	})
	if err != nil {
		return err
	}
	synthesis, err := experience.Synthesize(cmd.Context(), client, provider, opt.model, exp, docs, time.Now())
	if err != nil {
		return err
	}
	if err := experience.SaveCachedSynthesis(opt.cacheDir, synthesis); err != nil {
		return err
	}
	path := experience.SynthesisCachePath(opt.cacheDir, exp.Project)
	fmt.Fprintln(cmd.OutOrStdout(), path)
	fmt.Fprintf(cmd.ErrOrStderr(), "synthesized: project=%s provider=%s model=%s docs=%d unverified=true\n",
		exp.Project, synthesis.Provider, emptyDash(synthesis.Model), len(synthesis.DocIDs))
	if synthesis.Usage != nil {
		fmt.Fprintf(cmd.ErrOrStderr(), "usage: %s\n", formatUsage(*synthesis.Usage))
	}
	return nil
}

func loadExperienceContext(cacheDir string) (*cache.Store, []cache.DocInfo, *experience.State, []string, error) {
	store := &cache.Store{Root: cacheDir}
	infos, warnings := store.ListActiveDocs()
	state, err := experience.LoadState(experience.StatePath(cacheDir))
	if err != nil {
		return store, infos, experience.NewState(), warnings, err
	}
	return store, infos, state, warnings, nil
}

func findExperience(exps []experience.Experience, selector string) (*experience.Experience, error) {
	selector = strings.TrimSpace(selector)
	if selector == "" {
		selector = resolveAgentProject("auto")
	}
	if selector == "" {
		return nil, errors.New("--project is required (cannot infer it from the current directory)")
	}
	return experience.FindWith(exps, selector, render.SafeProject)
}

func experienceDocPaths(infos []cache.DocInfo) map[string]string {
	docs := make([]*extract.Doc, 0, len(infos))
	for _, info := range infos {
		if info.Doc != nil {
			docs = append(docs, info.Doc)
		}
	}
	out := make(map[string]string, len(docs))
	for _, plan := range render.PlanDocs(docs) {
		out[plan.Doc.ID] = plan.Path
	}
	return out
}

func validExperiencePeriod(value string) bool {
	value = strings.TrimSpace(value)
	if value == "" {
		return true
	}
	for _, layout := range []string{"2006-01", "2006-01-02"} {
		if _, err := time.Parse(layout, value); err == nil {
			return true
		}
	}
	return false
}

func experienceKindSourceLabel(source string) string {
	switch strings.ToLower(strings.TrimSpace(source)) {
	case experience.KindSourceManual:
		return "manual"
	case experience.KindSourceSuggestion:
		return "suggestion"
	default:
		return "default"
	}
}
