package main

import (
	"fmt"
	"strings"

	"github.com/spf13/cobra"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/export"
)

type renderOptions struct {
	cacheDir     string
	outDir       string
	includeStale bool
	profile      string
	prune        bool
}

func newRenderCmd() *cobra.Command {
	opt := &renderOptions{}
	cmd := &cobra.Command{
		Use:   "render",
		Short: "Render canonical Docs as Markdown with YAML front matter",
		Long: `Render every active document in the cache to
<out>/<project>/<date>-<slug>.md.

--profile agent (default) keeps the stable agent-facing Markdown.
--profile learning writes a Chinese learning template to *.learn.md (symptoms,
think-first prompts, diagnosis path, rejected hypotheses, root cause, fix,
verification, transferable method, knowledge cards, blind spots, checklist,
self-test questions with folded answers, and evidence sources). The agent
files are never overwritten.

Stale documents are skipped by default because they are no longer reproduced
by a current segment; their Doc JSON stays in the cache. Use --include-stale to
	render them anyway. Existing Markdown files are overwritten. With --prune,
	stale files previously generated by the same profile are removed only when
	their content still matches the output manifest. Unregistered or user-
	modified files are always kept.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return runRender(cmd, opt)
		},
	}
	cmd.Flags().StringVar(&opt.cacheDir, "cache-dir", ".devlog-cache", "cache directory containing docs/")
	cmd.Flags().StringVar(&opt.outDir, "out", ".devlog-docs", "output directory for Markdown files")
	cmd.Flags().BoolVar(&opt.includeStale, "include-stale", false, "render stale documents too")
	cmd.Flags().StringVar(&opt.profile, "profile", "agent", "render profile: agent or learning")
	cmd.Flags().BoolVar(&opt.prune, "prune", false, "remove stale files previously generated by this profile")
	return cmd
}

func runRender(cmd *cobra.Command, opt *renderOptions) error {
	stdout := cmd.OutOrStdout()
	stderr := cmd.ErrOrStderr()

	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return err
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()
	report, err := export.RenderProfileWithOptions(store, opt.outDir, export.RenderProfileOptions{
		IncludeStale: opt.includeStale,
		Profile:      opt.profile,
		Prune:        opt.prune,
	})
	printDryRunWarnings(stderr, report.Warnings)
	if err != nil {
		return err
	}
	if report.Written == 0 {
		fmt.Fprintln(stderr, "no documents to render")
	} else {
		for _, path := range report.Paths {
			fmt.Fprintln(stdout, path)
		}
	}

	fmt.Fprintf(stderr, "summary: rendered=%d skipped_stale=%d pruned=%d prune_skipped=%d profile=%s out=%s\n",
		report.Written, report.StaleSkipped, report.Pruned, report.PruneSkipped,
		opt.profile, strings.TrimSpace(opt.outDir))
	return nil
}
