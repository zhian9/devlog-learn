package main

import (
	"fmt"
	"time"

	"github.com/spf13/cobra"

	"devlog-learn/internal/cache"
	"devlog-learn/internal/export"
	"devlog-learn/internal/index"
)

type indexOptions struct {
	cacheDir string
	outDir   string
	prune    bool
}

func newIndexCmd() *cobra.Command {
	opt := &indexOptions{}
	cmd := &cobra.Command{
		Use:   "index",
		Short: "Build global and per-project index.json/README.md files",
		Long: `Build <out>/index.json, <out>/README.md and one index.json/README.md per
project. Only active documents are indexed: stale documents stay on disk in
the cache and are excluded by default.

Related document links are computed read-only; indexes never merge or modify
Doc content. Run "render" first if you want the Markdown links to exist.

With --prune, stale index files previously generated by this command are
removed only when their content still matches the output manifest.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return runIndex(cmd, opt)
		},
	}
	cmd.Flags().StringVar(&opt.cacheDir, "cache-dir", ".devlog-cache", "cache directory containing docs/")
	cmd.Flags().StringVar(&opt.outDir, "out", ".devlog-docs", "output directory for index files")
	cmd.Flags().BoolVar(&opt.prune, "prune", false, "remove stale index files previously generated by this command")
	return cmd
}

func runIndex(cmd *cobra.Command, opt *indexOptions) error {
	stdout := cmd.OutOrStdout()
	stderr := cmd.ErrOrStderr()

	store, err := cache.Open(opt.cacheDir)
	if err != nil {
		return err
	}
	lock, err := cache.TryLock(opt.cacheDir)
	if err != nil {
		return err
	}
	defer lock.Close()
	report, warnings, err := export.BuildIndexWithOptions(store, opt.outDir, time.Now(), index.WriteOptions{
		Prune: opt.prune,
	})
	printDryRunWarnings(stderr, warnings)

	if report.GlobalJSON != "" {
		fmt.Fprintln(stdout, report.GlobalJSON)
	}
	if report.GlobalReadme != "" {
		fmt.Fprintln(stdout, report.GlobalReadme)
	}
	for _, path := range report.ProjectJSON {
		fmt.Fprintln(stdout, path)
	}
	for _, path := range report.ProjectReadme {
		fmt.Fprintln(stdout, path)
	}
	if err != nil {
		return err
	}

	fmt.Fprintf(stderr, "summary: docs=%d projects=%d pruned=%d prune_skipped=%d out=%s\n",
		report.Docs, report.Projects, report.Pruned, report.PruneSkipped, opt.outDir)
	return nil
}
